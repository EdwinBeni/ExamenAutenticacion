    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        
String usuario = txtUsuario.getText().trim();

char[] caracteres = txtPassword.getPassword();
String password = new String(caracteres);
Arrays.fill(caracteres, '\0');

if (usuario.isEmpty() || password.isEmpty()) {
    JOptionPane.showMessageDialog(
        this, "Ingresa usuario y contraseña"
    );
    return;
}

try {
    String passwordCodificada = codificarPassword(password);

    // Construimos el JSON con las credenciales.
    String json = "{\"usuario\":\"" +
        usuario.replace("\\", "\\\\")
               .replace("\"", "\\\"") +
        "\",\"password\":\"" + passwordCodificada + "\"}";

    HttpClient cliente = HttpClient.newHttpClient();

    HttpRequest solicitud = HttpRequest.newBuilder()
        .uri(URI.create("http://localhost:8080/api/autenticar"))
        .header("Content-Type", "application/json")
        .POST(HttpRequest.BodyPublishers.ofString(
            json, StandardCharsets.UTF_8))
        .build();

    HttpResponse<String> respuesta = cliente.send(
        solicitud,
        HttpResponse.BodyHandlers.ofString()
    );

    if (respuesta.statusCode() == 200) {

        lblEstado.setText("Autenticación exitosa");

        JOptionPane.showMessageDialog(
            this, "Bienvenido al sistema"
        );

    } else if (respuesta.statusCode() == 401) {

        lblEstado.setText("Credenciales incorrectas");

        JOptionPane.showMessageDialog(
            this, "Usuario o contraseña incorrectos"
        );

    } else {

        lblEstado.setText("Error HTTP: " +
            respuesta.statusCode());

        JOptionPane.showMessageDialog(
            this, respuesta.body()
        );
    }

} catch (Exception ex) {

    lblEstado.setText("Error de conexión");

    JOptionPane.showMessageDialog(
        this,
        "No se pudo conectar con la API:\n" +
        ex.getMessage()
    );
}

    }//GEN-LAST:event_btnLoginActionPerformed

